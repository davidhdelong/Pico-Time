#!/usr/bin/env python3
"""Generate a small, deterministic, offline timezone database for the Pico.

The geographic input is the timezone-boundary-builder GeoJSON.  Rules are
derived from the host IANA tzdb through Python's zoneinfo module and are
expanded only for the supported year range.  The output is plain C data in
generated/timezone_data.{h,c}; the firmware never parses JSON or downloads
timezone data.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import pathlib
import re
import urllib.request
import zipfile

from shapely.geometry import shape

DEFAULT_URL = "https://github.com/evansiroky/timezone-boundary-builder/releases/download/2026f/timezones-1970.geojson.zip"
BOUNDARY_VERSION = "2026f"


def tzdb_version() -> str:
    try:
        first = pathlib.Path('/usr/share/zoneinfo/tzdata.zi').read_text().splitlines()[0]
        if first.startswith('# version '): return first.split()[-1]
    except OSError:
        pass
    return 'unknown'


def cstr(s: str) -> str:
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def epoch(x: dt.datetime) -> int:
    return int(x.replace(tzinfo=dt.timezone.utc).timestamp())


def offset_at(zone, seconds: int):
    x = dt.datetime.fromtimestamp(seconds, dt.timezone.utc).astimezone(zone)
    off = int(x.utcoffset().total_seconds())
    dst = bool(x.dst() and x.dst().total_seconds() != 0)
    return off, dst


def transitions(zone_name: str, start_year: int, end_year: int):
    from zoneinfo import ZoneInfo
    zone = ZoneInfo(zone_name)
    start = epoch(dt.datetime(start_year, 1, 1))
    end = epoch(dt.datetime(end_year + 1, 1, 1))
    result = [(*offset_at(zone, start), start)]
    old = result[0][:2]
    day = 86400
    t = start + day
    while t <= end:
        cur = offset_at(zone, t)
        if cur != old:
            lo, hi = t - day, t
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if offset_at(zone, mid) == old:
                    lo = mid
                else:
                    hi = mid
            result.append((cur[0], cur[1], hi))
            old = cur
        t += day
    return result


def load_geo(path: pathlib.Path):
    with zipfile.ZipFile(path) as z:
        names = [n for n in z.namelist() if n.endswith('.json')]
        if not names:
            raise RuntimeError('boundary archive contains no JSON')
        data = json.loads(z.read(names[0]))
    return data['features']


def rings_for_geometry(geometry, zone_index, tolerance):
    geom = shape(geometry).simplify(tolerance, preserve_topology=True)
    polys = list(geom.geoms) if geom.geom_type == 'MultiPolygon' else [geom]
    rings = []
    for poly in polys:
        for ring, hole in [(poly.exterior, 0), *[(r, 1) for r in poly.interiors]]:
            coords = [(int(round(x * 1e5)), int(round(y * 1e5))) for x, y in ring.coords[:-1]]
            if len(coords) >= 3:
                xs = [x for x, _ in coords]; ys = [y for _, y in coords]
                rings.append((zone_index, hole, min(xs), max(xs), min(ys), max(ys), coords))
    return rings


def generate(args):
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    source = pathlib.Path(args.geojson)
    if not source.exists():
        source.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(args.url, source)
    features = load_geo(source)
    zones = sorted({f['properties']['tzid'] for f in features})
    zone_id = {name: i + 1 for i, name in enumerate(zones)}  # 0 is ocean/UTC
    polygons = []
    for f in features:
        name = f['properties']['tzid']
        polygons.extend(rings_for_geometry(f['geometry'], zone_id[name], args.tolerance))

    rule_rows = []
    zone_rows = []
    for name in zones:
        first = len(rule_rows)
        for off, dst, when in transitions(name, args.start, args.end):
            rule_rows.append((when, off, int(dst)))
        zone_rows.append((zone_id[name], first, len(rule_rows) - first, name))

    h = out / 'timezone_data.h'
    c = out / 'timezone_data.c'
    with h.open('w') as f:
        f.write('/* Generated by tools/timezone_generator/generate.py. */\n')
        f.write('#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n')
        f.write(f'#define TZDB_VERSION "{tzdb_version()}"\n#define TZ_BOUNDARY_VERSION "{BOUNDARY_VERSION}"\n')
        f.write(f'#define TZ_DATA_START_YEAR {args.start}\n#define TZ_DATA_END_YEAR {args.end}\n')
        f.write('typedef struct { int32_t lon_e5, lat_e5; } tz_point_t;\n')
        f.write('typedef struct { uint16_t zone; uint16_t count; uint32_t first; int32_t min_lon,max_lon,min_lat,max_lat; uint8_t hole; } tz_ring_t;\n')
        f.write('typedef struct { uint32_t epoch; int32_t offset; uint8_t dst; } tz_transition_t;\n')
        f.write('typedef struct { uint16_t id; uint32_t first; uint16_t count; const char *name; } tz_zone_t;\n')
        f.write('extern const tz_point_t tz_points[]; extern const size_t tz_point_count;\n')
        f.write('extern const tz_ring_t tz_rings[]; extern const size_t tz_ring_count;\n')
        f.write('extern const tz_transition_t tz_transitions[]; extern const size_t tz_transition_count;\n')
        f.write('extern const tz_zone_t tz_zones[]; extern const size_t tz_zone_count;\n')
    with c.open('w') as f:
        f.write('/* Generated data: geographic boundaries and precomputed UTC transitions. */\n#include "timezone_data.h"\n\n')
        points = []
        ring_rows = []
        for zid, hole, minx, maxx, miny, maxy, coords in polygons:
            first = len(points); points.extend((x, y) for x, y in coords)
            ring_rows.append((zid, len(coords), first, minx, maxx, miny, maxy, hole))
        f.write('const tz_point_t tz_points[] = {\n')
        for x, y in points: f.write(f'  {{{x}, {y}}},\n')
        f.write('};\nconst size_t tz_point_count = sizeof(tz_points)/sizeof(tz_points[0]);\n')
        f.write('const tz_ring_t tz_rings[] = {\n')
        for row in ring_rows: f.write('  {%d,%d,%d,%d,%d,%d,%d,%d},\n' % row)
        f.write('};\nconst size_t tz_ring_count = sizeof(tz_rings)/sizeof(tz_rings[0]);\n')
        f.write('const tz_transition_t tz_transitions[] = {\n')
        for when, off, dst in rule_rows: f.write(f'  {{{when}u,{off},{dst}}},\n')
        f.write('};\nconst size_t tz_transition_count = sizeof(tz_transitions)/sizeof(tz_transitions[0]);\n')
        f.write('const tz_zone_t tz_zones[] = {\n')
        for zid, first, count, name in zone_rows: f.write(f'  {{{zid},{first},{count},{cstr(name)}}},\n')
        f.write('};\nconst size_t tz_zone_count = sizeof(tz_zones)/sizeof(tz_zones[0]);\n')
    print(f'zones={len(zones)} rings={len(polygons)} points={sum(len(x[-1]) for x in polygons)} transitions={len(rule_rows)}')


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--geojson', default='tools/timezone_generator/timezones-1970.geojson.zip')
    ap.add_argument('--url', default=DEFAULT_URL)
    ap.add_argument('--out', default='generated')
    ap.add_argument('--start', type=int, default=2020)
    ap.add_argument('--end', type=int, default=2050)
    ap.add_argument('--tolerance', type=float, default=0.02, help='polygon simplification in degrees')
    generate(ap.parse_args())
